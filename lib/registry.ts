/** Get a tool by slug */
export function getTool(slug: string): ToolDefinition | undefined {
  return tools.find((t) => t.slug === slug);
}

/** Get all tools in a category */
export function getToolsByCategory(category: Category): ToolDefinition[] {
  return tools.filter((t) => t.category === category);
}

/** Get all categories that have tools */
export function getActiveCategories(): Category[] {
  const cats = new Set(tools.map((t) => t.category));
  return Array.from(cats) as Category[];
}

/** Search tools by query */
export function searchTools(query: string): ToolDefinition[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return tools
    .filter((t) => {
      const haystack = [
        t.title,
        t.shortDescription,
        ...(t.keywords || []),
        ...(t.aliases || []),
        t.category,
      ]
        .join(' ')
        .toLowerCase();
      return haystack.includes(q);
    })
    .slice(0, 10);
}

/** Get related tools by slugs */
export function getRelatedTools(slugs: string[]): ToolDefinition[] {
  return slugs
    .map((s) => getTool(s))
    .filter((t): t is ToolDefinition => t !== undefined);
}

