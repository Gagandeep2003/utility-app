/** Validate all tools have required metadata */
export function validateTools(): { valid: boolean; errors: string[] } {
  const errors: string[] = [];
  const slugs = new Set<string>();

  for (const tool of tools) {
    if (!tool.id) errors.push(`Tool missing id`);
    if (!tool.slug) errors.push(`Tool "${tool.id}" missing slug`);
    if (slugs.has(tool.slug)) errors.push(`Duplicate slug: ${tool.slug}`);
    slugs.add(tool.slug);
    if (!tool.title) errors.push(`Tool "${tool.id}" missing title`);
    if (!tool.shortDescription) errors.push(`Tool "${tool.id}" missing shortDescription`);
    if (!tool.category) errors.push(`Tool "${tool.id}" missing category`);
    if (!tool.computation) errors.push(`Tool "${tool.id}" missing computation`);
    if (tool.keywords.length === 0) errors.push(`Tool "${tool.id}" has no keywords`);
    if (!tool.formula) errors.push(`Tool "${tool.id}" missing formula`);
    if (!tool.explanation) errors.push(`Tool "${tool.id}" missing explanation`);
    if (tool.examples.length === 0) errors.push(`Tool "${tool.id}" has no examples`);
    if (tool.relatedTools.length === 0) errors.push(`Tool "${tool.id}" has no related tools`);

    // Check related tools exist
    for (const relatedSlug of tool.relatedTools) {
      if (!getTool(relatedSlug)) {
        errors.push(`Tool "${tool.id}" references non-existent related tool: ${relatedSlug}`);
      }
    }
  }

  return { valid: errors.length === 0, errors };
}
